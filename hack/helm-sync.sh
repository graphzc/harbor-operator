#!/usr/bin/env bash
# Copies the controller-gen output (CRDs and the manager ClusterRole rules)
# into the Helm chart so the chart never drifts from the code.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
chart="$root/charts/harbor-operator"

rm -f "$chart"/templates/crds/*.yaml
for crd in "$root"/config/crd/bases/*.yaml; do
  out="$chart/templates/crds/$(basename "$crd")"
  {
    echo "# Generated by hack/helm-sync.sh from config/crd/bases. DO NOT EDIT."
    echo "{{- if .Values.crds.install }}"
    # Keep CRDs on uninstall when crds.keep is set, so Harbor resources survive.
    sed -e '/^  annotations:$/a\
{{- if .Values.crds.keep }}\
    helm.sh/resource-policy: keep\
{{- end }}' "$crd"
    echo "{{- end }}"
  } > "$out"
done

{
  echo "# Generated by hack/helm-sync.sh from config/rbac/role.yaml. DO NOT EDIT."
  sed -n '/^rules:/,$p' "$root/config/rbac/role.yaml"
} > "$chart/files/manager-rules.yaml"

echo "Synced CRDs and RBAC rules into $chart"
