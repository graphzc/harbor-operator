package v1alpha1

import (
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
)

// RobotLevel is the scope of a robot account.
// +kubebuilder:validation:Enum=system;project
type RobotLevel string

const (
	RobotLevelSystem  RobotLevel = "system"
	RobotLevelProject RobotLevel = "project"
)

// RobotAccess is a single resource/action pair, e.g. repository/pull.
type RobotAccess struct {
	// Resource, e.g. repository, artifact, tag, helm-chart, scan.
	// +kubebuilder:validation:MinLength=1
	Resource string `json:"resource"`

	// Action, e.g. pull, push, read, list, create, delete.
	// +kubebuilder:validation:MinLength=1
	Action string `json:"action"`

	// Effect of the access rule.
	// +kubebuilder:validation:Enum=allow;deny
	// +optional
	Effect string `json:"effect,omitempty"`
}

// RobotPermission grants access on a namespace (project) or the system.
type RobotPermission struct {
	// Kind of the permission target.
	// +kubebuilder:validation:Enum=project;system
	// +kubebuilder:default=project
	// +optional
	Kind string `json:"kind,omitempty"`

	// Namespace is the project name, "*" for all projects, or "/" for system
	// permissions. For project-level robots it defaults to spec.project.
	// +optional
	Namespace string `json:"namespace,omitempty"`

	// Access rules granted.
	// +kubebuilder:validation:MinItems=1
	Access []RobotAccess `json:"access"`
}

// RobotAccountSpec defines the desired state of a Harbor robot account.
// +kubebuilder:validation:XValidation:rule="self.name == oldSelf.name",message="name is immutable"
// +kubebuilder:validation:XValidation:rule="self.level == oldSelf.level",message="level is immutable"
// +kubebuilder:validation:XValidation:rule="self.level != 'project' || (has(self.project) && size(self.project) > 0)",message="project is required for project-level robots"
type RobotAccountSpec struct {
	// HarborConnectionRef selects the Harbor instance.
	HarborConnectionRef HarborConnectionReference `json:"harborConnectionRef"`

	// Name of the robot, without the Harbor robot prefix. Immutable.
	// +kubebuilder:validation:Pattern=`^[a-z0-9]+(?:[._-][a-z0-9]+)*$`
	Name string `json:"name"`

	// Level of the robot. Immutable.
	// +kubebuilder:default=system
	// +optional
	Level RobotLevel `json:"level,omitempty"`

	// Project the robot belongs to (project-level robots only).
	// +optional
	Project string `json:"project,omitempty"`

	// Description of the robot.
	// +optional
	Description string `json:"description,omitempty"`

	// Duration of the robot in days; -1 never expires.
	// +kubebuilder:default=-1
	// +optional
	Duration int64 `json:"duration,omitempty"`

	// Disabled disables the robot.
	// +optional
	Disabled bool `json:"disabled,omitempty"`

	// Permissions granted to the robot.
	// +kubebuilder:validation:MinItems=1
	Permissions []RobotPermission `json:"permissions"`

	// SecretRef selects an existing Secret key holding the robot secret.
	// When omitted, the secret generated by Harbor is stored in GeneratedSecret.
	// Harbor requires 8-128 characters with upper case, lower case and a number.
	// +optional
	SecretRef *SecretKeySelector `json:"secretRef,omitempty"`

	// GeneratedSecret configures the Secret holding the robot credentials.
	// The Secret holds the keys "username" and "password".
	// +optional
	GeneratedSecret GeneratedSecret `json:"generatedSecret,omitempty"`

	// DeletionPolicy controls whether the Harbor robot is removed with this resource.
	// +kubebuilder:default=Delete
	// +optional
	DeletionPolicy DeletionPolicy `json:"deletionPolicy,omitempty"`
}

// RobotAccountStatus defines the observed state of RobotAccount.
type RobotAccountStatus struct {
	HarborResourceStatus `json:",inline"`

	// RobotID is the Harbor robot ID.
	// +optional
	RobotID int64 `json:"robotID,omitempty"`

	// FullName is the robot name as used to log in, e.g. robot$name.
	// +optional
	FullName string `json:"fullName,omitempty"`

	// ExpiresAt is when the robot expires; unset when it never expires.
	// +optional
	ExpiresAt *metav1.Time `json:"expiresAt,omitempty"`

	// SecretName is the Secret holding the robot credentials.
	// +optional
	SecretName string `json:"secretName,omitempty"`

	// SecretHash is a hash of the last secret applied to Harbor.
	// +optional
	SecretHash string `json:"secretHash,omitempty"`
}

// +kubebuilder:object:root=true
// +kubebuilder:subresource:status
// +kubebuilder:resource:shortName=hra
// +kubebuilder:printcolumn:name="Robot",type=string,JSONPath=`.status.fullName`
// +kubebuilder:printcolumn:name="Level",type=string,JSONPath=`.spec.level`
// +kubebuilder:printcolumn:name="Project",type=string,JSONPath=`.spec.project`
// +kubebuilder:printcolumn:name="Ready",type=string,JSONPath=`.status.conditions[?(@.type=="Ready")].status`
// +kubebuilder:printcolumn:name="Age",type=date,JSONPath=`.metadata.creationTimestamp`

// RobotAccount is a Harbor robot account, either system-wide or scoped to a project.
type RobotAccount struct {
	metav1.TypeMeta   `json:",inline"`
	metav1.ObjectMeta `json:"metadata,omitempty"`

	Spec   RobotAccountSpec   `json:"spec,omitempty"`
	Status RobotAccountStatus `json:"status,omitempty"`
}

// +kubebuilder:object:root=true

// RobotAccountList contains a list of RobotAccount.
type RobotAccountList struct {
	metav1.TypeMeta `json:",inline"`
	metav1.ListMeta `json:"metadata,omitempty"`
	Items           []RobotAccount `json:"items"`
}

func init() {
	SchemeBuilder.Register(&RobotAccount{}, &RobotAccountList{})
}
